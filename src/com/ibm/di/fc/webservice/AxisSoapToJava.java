/**
 * The Axis Soap-to-Java Function Component (FC) is part of the 
 * TDI Web Services suite.This component can be used both on the web 
 * service client and on the web service server side. This FC uses 
 * Axis2's mechanism for parsing SOAP response (when on the client) 
 * or SOAP request (when on the server) to Java objects - as a 
 * complementary component to the AxisJavaToSoap FC. It is given a 
 * SOAP response/request message and returns the parsed Java objects 
 * either as standalone Java object(s) or capsulated in an 
 * Entry object.This component supports both RPC and Document style.
 *
 */
